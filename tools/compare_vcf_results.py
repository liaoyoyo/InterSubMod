def parse_args():
    parser = argparse.ArgumentParser(description="Advanced Comparison of InterSubMod VCF analysis outputs.")
    parser.add_argument("--output-dir", required=True, help="Directory to save analysis results")
    parser.add_argument("--labels", nargs='+', required=True, help="List of labels for the inputs (e.g., TP FP)")
    parser.add_argument("--paths", nargs='+', required=True, help="List of paths to the output directories corresponding to labels")
    return parser.parse_args()


def load_data(labels, paths):
    """Load significance_summary.csv from each path."""
    dfs = []
    
    for label, path in zip(labels, paths):
        csv_path = os.path.join(path, "significance_summary.csv")
        logger.info(f"Loading data from {csv_path} ({label})...")
        
        if not os.path.exists(csv_path):
            logger.error(f"Metadata file not found: {csv_path}")
            # Try recursive search if file not in root
            found_files = []
            for root, dirs, files in os.walk(path):
                if "significance_summary.csv" in files:
                    found_files.append(os.path.join(root, "significance_summary.csv"))
            
            if found_files:
                csv_path = found_files[0]
                logger.info(f"Found file at nested path: {csv_path}")
            else:
                logger.warning(f"Skipping {label}: No significance_summary.csv found.")
                continue

        try:
            df = pd.read_csv(csv_path)
            df['Label'] = label
            dfs.append(df)
            logger.info(f"  Loaded {len(df)} records for {label}")
        except Exception as e:
            logger.error(f"Failed to read CSV for {label}: {e}")
            
    if not dfs:
        return pd.DataFrame()
        
    return pd.concat(dfs, ignore_index=True)


def setup_output_dirs(output_dir):
    """Create organized output directory structure."""
    dirs = {
        'tables': os.path.join(output_dir, 'tables'),
        'distribution': os.path.join(output_dir, 'plots', 'distribution'),
        'correlation': os.path.join(output_dir, 'plots', 'correlation'),
        'evaluation': os.path.join(output_dir, 'plots', 'evaluation'),
        'heatmaps': os.path.join(output_dir, 'plots', 'heatmaps'),
    }
    for d in dirs.values():
        os.makedirs(d, exist_ok=True)
    return dirs


def generate_summary_stats(df, dirs):
    """Generate summary statistics."""
    logger.info("Generating summary statistics...")
    
    # Basic groupby stats
    stats = df.groupby('Label').agg({
        'RegionID': 'count',
        'NumReads': ['mean', 'median', 'std'],
        'NumCpGs': ['mean', 'median'],
        'GlobalP': ['mean', 'median'],
        'CramersV': ['mean', 'median', 'max'],
        'LabelDelta': ['mean', 'median'],
        'Significant': lambda x: (x == True).sum()
    }).reset_index()
    
    # Rename columns for clarity (flatten MultiIndex)
    stats.columns = ['Label', 'Count', 'Reads_Mean', 'Reads_Median', 'Reads_Std',
                     'CpGs_Mean', 'CpGs_Median',
                     'P_Mean', 'P_Median', 
                     'V_Mean', 'V_Median', 'V_Max',
                     'Delta_Mean', 'Delta_Median',
                     'Sig_Count']
    
    stats['Sig_Rate_%'] = (stats['Sig_Count'] / stats['Count']) * 100
    
    save_path = os.path.join(dirs['tables'], "summary_stats.csv")
    stats.to_csv(save_path, index=False)
    logger.info(f"Summary stats saved to {save_path}")
    print("\n=== Summary Stats ===\n")
    print(stats.to_string())
    print("\n")
    
    return stats


def generate_verification_class_stats(df, dirs):
    """Generate VerificationClass breakdown statistics."""
    logger.info("Generating VerificationClass breakdown...")
    
    if 'VerificationClass' not in df.columns:
        logger.warning("VerificationClass column not found, skipping.")
        return None
    
    # Cross-tabulation with proportions
    crosstab = pd.crosstab(df['Label'], df['VerificationClass'], margins=True)
    crosstab_pct = pd.crosstab(df['Label'], df['VerificationClass'], normalize='index') * 100
    
    save_path = os.path.join(dirs['tables'], "verification_class_breakdown.csv")
    crosstab.to_csv(save_path)
    
    save_path_pct = os.path.join(dirs['tables'], "verification_class_percentage.csv")
    crosstab_pct.to_csv(save_path_pct)
    
    logger.info(f"VerificationClass breakdown saved to {save_path}")
    print("\n=== VerificationClass Breakdown (%) ===\n")
    print(crosstab_pct.to_string())
    print("\n")
    
    return crosstab_pct


