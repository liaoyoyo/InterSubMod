    plt.ylabel("Percentage (%)")
    plt.legend(title="Class", bbox_to_anchor=(1.05, 1), loc='upper left')
    plt.xticks(rotation=0)
    plt.tight_layout()
    plt.savefig(os.path.join(plot_dir, "dist_verification_class.png"), dpi=150)
    plt.close()


