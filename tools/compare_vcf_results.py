def plot_roc_curves(df, dirs):
    """
    Generate ROC curves assuming one label is Positive (TP) and others are Negative (FP).
    """
    logger.info("Generating ROC curves...")
    plot_dir = dirs['evaluation']
    
    unique_labels = df['Label'].unique()
    if len(unique_labels) != 2:
        logger.warning("ROC analysis requires exactly 2 labels. Skipping.")
        return []
        
    # Identify Positive/Negative class
    pos_label = None
    neg_label = None
    
    for l in unique_labels:
        if 'tp' in l.lower() or 'tumor' in l.lower():
            pos_label = l
        elif 'fp' in l.lower() or 'normal' in l.lower() or 'control' in l.lower():
            neg_label = l
            
    if not pos_label or not neg_label:
        pos_label = unique_labels[0]
        neg_label = unique_labels[1]
        
    logger.info(f"ROC Analysis: Positive Class = '{pos_label}', Negative Class = '{neg_label}'")
    
    # Create binary target (1=Pos, 0=Neg)
    df_roc = df[df['Label'].isin([pos_label, neg_label])].copy()
    df_roc['target'] = (df_roc['Label'] == pos_label).astype(int)
    
    metrics_to_test = {
        'CramersV': 'Cramér\'s V',
        'HeuristicScore': 'Heuristic Score',
        'LogP': '-log10(P-value)',
        'LabelDelta': 'Label Delta'
    }
    
    # Pre-calc LogP
    df_roc['LogP'] = -np.log10(df_roc['GlobalP'].replace(0, 1e-15))
    
    plt.figure(figsize=(8, 8))
    
    csv_rows = []
    
    for metric, name in metrics_to_test.items():
        if metric not in df_roc.columns:
            continue
            
        try:
            fpr, tpr, thresholds = sk_metrics.roc_curve(df_roc['target'], df_roc[metric])
            auc = sk_metrics.auc(fpr, tpr)
            
            plt.plot(fpr, tpr, label=f'{name} (AUC = {auc:.3f})')
            
            # Find optimal threshold (Youden's J statistic)
            J = tpr - fpr
            ix = np.argmax(J)
            best_thresh = thresholds[ix]
            
            csv_rows.append({
                'Metric': name,
                'AUC': auc,
                'BestThreshold': best_thresh,
                'Sensitivity': tpr[ix],
                'Specificity': 1 - fpr[ix]
            })
            
        except Exception as e:
            logger.warning(f"Failed ROC for {metric}: {e}")
            
    plt.plot([0, 1], [0, 1], 'k--')
    plt.xlim([0.0, 1.0])
    plt.ylim([0.0, 1.05])
    plt.xlabel('False Positive Rate')
    plt.ylabel('True Positive Rate')
    plt.title('ROC Curves for TP/FP Discrimination')
    plt.legend(loc="lower right")
    plt.savefig(os.path.join(plot_dir, "roc_curves.png"), dpi=150)
    plt.close()
    
    # Save ROC Metrics
    metrics_df = pd.DataFrame(csv_rows)
    metrics_path = os.path.join(dirs['tables'], "discrimination_metrics.csv")
    metrics_df.to_csv(metrics_path, index=False)
    logger.info(f"Discrimination metrics saved to {metrics_path}")
    print("\n=== Discrimination Metrics ===\n")
    print(metrics_df.to_string())
    print("\n")
    
    return csv_rows


def plot_precision_recall(df, dirs):
    """Generate Precision-Recall curves for imbalanced data."""
    logger.info("Generating Precision-Recall curves...")
    plot_dir = dirs['evaluation']
    
    unique_labels = df['Label'].unique()
    if len(unique_labels) != 2:
        logger.warning("PR analysis requires exactly 2 labels. Skipping.")
        return
    
    # Identify Positive/Negative class (same logic as ROC)
    pos_label = None
    neg_label = None
    
    for l in unique_labels:
        if 'tp' in l.lower():
            pos_label = l
        elif 'fp' in l.lower():
            neg_label = l
            
    if not pos_label or not neg_label:
        pos_label = unique_labels[0]
        neg_label = unique_labels[1]
    
    df_pr = df[df['Label'].isin([pos_label, neg_label])].copy()
    df_pr['target'] = (df_pr['Label'] == pos_label).astype(int)
    
    metrics_to_test = ['CramersV', 'HeuristicScore', 'LabelDelta']
    
    # Pre-calc LogP
    df_pr['LogP'] = -np.log10(df_pr['GlobalP'].replace(0, 1e-15))
    
    plt.figure(figsize=(8, 8))
    
    for metric in metrics_to_test:
        if metric not in df_pr.columns:
            continue
            
        try:
            precision, recall, _ = sk_metrics.precision_recall_curve(df_pr['target'], df_pr[metric])
            ap = sk_metrics.average_precision_score(df_pr['target'], df_pr[metric])
            plt.plot(recall, precision, label=f'{metric} (AP = {ap:.3f})')
        except Exception as e:
            logger.warning(f"Failed PR for {metric}: {e}")
    
    plt.xlabel('Recall')
    plt.ylabel('Precision')
    plt.title('Precision-Recall Curves')
    plt.legend(loc="lower left")
    plt.savefig(os.path.join(plot_dir, "precision_recall.png"), dpi=150)
    plt.close()


def df_to_md_table(df, index=True):
    """Convert DataFrame to markdown table without tabulate dependency."""
    if index:
        df = df.reset_index()
    
    # Build header
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    separator = "|" + "|".join("---" for _ in df.columns) + "|"
    
    # Build rows
    rows = []
    for _, row in df.iterrows():
        row_str = "| " + " | ".join(f"{v:.4f}" if isinstance(v, float) else str(v) for v in row) + " |"
        rows.append(row_str)
    
    return "\n".join([header, separator] + rows)


def generate_report(df, stats, dirs, output_dir, roc_metrics):
    """Generate a markdown report summarizing the analysis."""
    logger.info("Generating analysis report...")
    
    report_path = os.path.join(output_dir, "report.md")
    
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write(f"# TP/FP 比較分析報告\n\n")
        f.write(f"> 生成時間: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
        f.write("---\n\n")
        
        f.write("## 1. 統計彙總\n\n")
        f.write(df_to_md_table(stats, index=False))
        f.write("\n\n")
        
        # VerificationClass breakdown
        if 'VerificationClass' in df.columns:
            f.write("## 2. VerificationClass 分布 (%)\n\n")
            crosstab_pct = pd.crosstab(df['Label'], df['VerificationClass'], normalize='index') * 100
            f.write(df_to_md_table(crosstab_pct, index=True))
            f.write("\n\n")
        
        # DominantLabel breakdown
        if 'DominantLabel' in df.columns:
            f.write("## 3. DominantLabel 分布 (%)\n\n")
            crosstab_pct = pd.crosstab(df['Label'], df['DominantLabel'], normalize='index') * 100
            f.write(df_to_md_table(crosstab_pct, index=True))
            f.write("\n\n")
        
        # ROC Metrics
        if roc_metrics:
            f.write("## 4. ROC 鑑別力分析\n\n")
            metrics_df = pd.DataFrame(roc_metrics)
            f.write(df_to_md_table(metrics_df, index=False))
            f.write("\n\n")
        
        # Generated plots list
        f.write("## 5. 產生的圖表\n\n")
        f.write("### 分布圖 (plots/distribution/)\n")
        for img in os.listdir(dirs['distribution']):
            f.write(f"- `{img}`\n")
        f.write("\n### 相關性圖 (plots/correlation/)\n")
        for img in os.listdir(dirs['correlation']):
            f.write(f"- `{img}`\n")
        f.write("\n### 評估圖 (plots/evaluation/)\n")
        for img in os.listdir(dirs['evaluation']):
            f.write(f"- `{img}`\n")
        if os.listdir(dirs['heatmaps']):
            f.write("\n### 熱圖 (plots/heatmaps/)\n")
            for img in os.listdir(dirs['heatmaps']):
                f.write(f"- `{img}`\n")
        f.write("\n")
    
    logger.info(f"Report saved to {report_path}")


def main():
    args = parse_args()
    
    # Setup directories
    dirs = setup_output_dirs(args.output_dir)
    
    if len(args.labels) != len(args.paths):
        logger.error("Error: Number of labels must match number of paths.")
        sys.exit(1)
        
    logger.info("Starting analysis...")
    
    df = load_data(args.labels, args.paths)
    
    if df.empty:
        logger.error("No data collected. Please check input directories and ensure significance_summary.csv exists.")
        sys.exit(1)
    
    logger.info(f"Total records loaded: {len(df)}")
    
    # Run analyses
    stats = generate_summary_stats(df, dirs)
    generate_verification_class_stats(df, dirs)
    generate_dominant_label_stats(df, dirs)
    
    # Plotting
    plot_distributions(df, dirs)
    plot_verification_class(df, dirs)
    plot_dominant_label_dist(df, dirs)
    plot_correlations(df, dirs)
    plot_cross_heatmap(df, dirs)
    roc_metrics = plot_roc_curves(df, dirs)
    plot_precision_recall(df, dirs)
    
    # Generate report
    generate_report(df, stats, dirs, args.output_dir, roc_metrics)
    
    logger.info("Analysis complete.")


if __name__ == "__main__":
    main()
