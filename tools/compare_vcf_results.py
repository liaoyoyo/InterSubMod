"""
Compare VCF Results Tool (Advanced TP/FP Analysis)
Usage: python3 compare_vcf_results.py --output-dir <DIR> --labels <LABELS...> --paths <PATHS...>

This script performs a comprehensive comparison of TP and FP VCF analysis results.
It utilizes the `significance_summary.csv` generated by the C++ pipeline to analyze:
- Significance distribution (P-value, Cramers V)
- VerificationClass breakdown
- DominantLabel analysis
- Read depth and CpG correlation
- ROC curves for discrimination power
- Precision-Recall curves
"""

