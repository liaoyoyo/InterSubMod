def write_tsv(path: Path, rows: list[dict]) -> int:
    if not rows:
        path.write_text("")
        return 0
    headers = list(rows[0].keys())
    with path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=headers, delimiter="\t")
        w.writeheader()
        for r in rows:
            w.writerow(r)
    return len(rows) + 1  # data rows + header


