def fetch_hp_map(path: str, chrom: str, pos: int, window: int = WINDOW) -> dict[str, object]:
    """Return {read_name: HP_tag_value_or_None} for primary reads spanning pos.

    HP tag is returned untouched: integer (1, 2, 11, 21, 33) for BL/V3F/V5
    BAMs, or string ("1", "2", "1-1", "2-1", ...) for the paired BAM.
    """
    out: dict[str, object] = {}
    bam = pysam.AlignmentFile(path, "rb")
    try:
        for r in bam.fetch(chrom, max(0, pos - window), pos + window):
            if r.is_unmapped or r.is_secondary or r.is_supplementary:
                continue
            if r.reference_start > pos or r.reference_end < pos:
                continue
            try:
                hp = r.get_tag("HP")
            except KeyError:
                hp = None
            # Keep last occurrence (multi-segment reads share name; HP should agree).
            out[r.query_name] = hp
    finally:
        bam.close()
    return out


def paired_canonical(hp_z: object) -> str | None:
    """Map paired HP:Z string to canonical {"1", "2"}.

    Strings like "1", "1-1", "1-2" → "1"; "2", "2-1", "2-2" → "2".
    Empty / missing → None.
    """
    if hp_z is None:
        return None
    s = str(hp_z).strip()
    if not s:
        return None
    head = s.split("-", 1)[0]
    if head in ("1", "2"):
        return head
    return None


def germline_concordance(v3f_map: dict, paired_map: dict, swap: bool) -> tuple[int, int]:
    """Count germline reads (V3F HP∈{1,2}) where paired canonical agrees.

    With `swap=True` the paired side is flipped (1<->2) before comparison.
    Returns (matches, total_germline_with_paired).
    """
    flip = {"1": "2", "2": "1"}
    matches = 0
    total = 0
    for rn, hp in v3f_map.items():
        if hp not in (1, 2):
            continue
        p = paired_canonical(paired_map.get(rn))
        if p is None:
            continue
        total += 1
        if swap:
            p_use = flip[p]
        else:
            p_use = p
        if (hp == 1 and p_use == "1") or (hp == 2 and p_use == "2"):
            matches += 1
    return matches, total


def pick_orientation(v3f_map: dict, paired_map: dict) -> tuple[bool, float, int]:
    """Return (swap_paired, germline_acc, germline_n).

    Picks whichever orientation maximises germline concordance, tracked per
    site. If too few germline reads to decide (<3) the no-swap orientation is
    used by default and germline_acc is reported as-is.
    """
    m_no, t_no = germline_concordance(v3f_map, paired_map, swap=False)
    m_sw, t_sw = germline_concordance(v3f_map, paired_map, swap=True)
    if t_no == 0 and t_sw == 0:
        return False, float("nan"), 0
    acc_no = m_no / t_no if t_no else 0.0
    acc_sw = m_sw / t_sw if t_sw else 0.0
    if acc_sw > acc_no:
        return True, acc_sw, t_sw
    return False, acc_no, t_no


def read_concordance(track_map: dict, paired_map: dict, swap: bool) -> tuple[int, int]:
    """Count concordant reads where track HP∈{1,2,11,21} maps to paired canonical.

    HP11 collapses to "1" direction, HP21 to "2". HP33 reads are excluded
    (no committed direction). Reads without paired HP also excluded.
    """
    flip = {"1": "2", "2": "1"}
    matches = 0
    total = 0
    for rn, hp in track_map.items():
        if hp == 1 or hp == 11:
            track_dir = "1"
        elif hp == 2 or hp == 21:
            track_dir = "2"
        else:
            continue
        p = paired_canonical(paired_map.get(rn))
        if p is None:
            continue
        total += 1
        if swap:
            p = flip[p]
        if track_dir == p:
            matches += 1
    return matches, total


def fmt_pct(num: int, denom: int) -> str:
    if denom == 0:
        return "n/a"
    return f"{100.0 * num / denom:.1f}%"


# ---------------------------------------------------------------------------
# Per-site analysis
# ---------------------------------------------------------------------------
sanity_rows = []
paired_rows = []
transitions_global = Counter()       # (v3f_tag, v5_tag) -> count, aggregated
new_dir_from_germline = 0            # Layer 1.5 expectation 2 violations
new_dir_from_untagged = 0            # informational
delta_consistency_violations = 0     # Conservation Law A violations
germline_change_violations = 0       # Conservation Law B violations
layer15_pred1_violations = 0         # Layer 1.5 expectation 1 violations

for sid, chrom, pos, klass, _desc in SITES:
    bl = fetch_hp_map(BL_BAM, chrom, pos)
    v3 = fetch_hp_map(V3F_BAM, chrom, pos)
    v5 = fetch_hp_map(V5_BAM, chrom, pos)
    pa = fetch_hp_map(PAIRED_BAM, chrom, pos)

    common = set(v3) & set(v5)

    # --- Conservation Law A: ΔHP33 = -(ΔHP11 + ΔHP21) -----------------------
    def hp_count(m: dict, tag: int) -> int:
        return sum(1 for h in m.values() if h == tag)

    n_v3_33 = hp_count(v3, 33)
    n_v5_33 = hp_count(v5, 33)
    n_v3_11 = hp_count(v3, 11)
    n_v5_11 = hp_count(v5, 11)
    n_v3_21 = hp_count(v3, 21)
    n_v5_21 = hp_count(v5, 21)
    d_33 = n_v5_33 - n_v3_33
    d_11 = n_v5_11 - n_v3_11
    d_21 = n_v5_21 - n_v3_21
    law_a_pass = (d_33 == -(d_11 + d_21))
    if not law_a_pass:
        delta_consistency_violations += 1

    # --- Conservation Law B: HP1/HP2 unchanged ------------------------------
    n_v3_1 = hp_count(v3, 1)
    n_v5_1 = hp_count(v5, 1)
    n_v3_2 = hp_count(v3, 2)
    n_v5_2 = hp_count(v5, 2)
    law_b_pass = (n_v3_1 == n_v5_1) and (n_v3_2 == n_v5_2)
    if not law_b_pass:
        germline_change_violations += 1

    # --- Layer 1.5 read-level transitions -----------------------------------
    transitions = Counter()
    for rn in common:
        a = v3[rn]
        b = v5[rn]
        # Normalise None to 0 for tally readability.
        a_k = a if a is not None else 0
        b_k = b if b is not None else 0
        transitions[(a_k, b_k)] += 1
        transitions_global[(a_k, b_k)] += 1

    n_33to11 = transitions[(33, 11)]
    n_33to21 = transitions[(33, 21)]
    n_germ_to_33 = transitions[(1, 33)] + transitions[(2, 33)]
    n_unt_to_dir = transitions[(0, 11)] + transitions[(0, 21)]
    n_germ_changed = sum(c for (a, b), c in transitions.items() if a in (1, 2) and a != b)

    # Expectation 1: ΔHP11 == n_33to11 (and same for HP21). Allow a small
    # tolerance for reads added/removed to the common set (length differences
    # were 0 across all 15 sites in our probe but coded defensively).
    exp1_a = (d_11 == n_33to11)
    exp1_b = (d_21 == n_33to21)
    layer15_pred1_pass = exp1_a and exp1_b
    if not layer15_pred1_pass:
        layer15_pred1_violations += 1

    # Expectation 2: zero germline → HP33.
    layer15_pred2_pass = (n_germ_to_33 == 0)
    if not layer15_pred2_pass:
        new_dir_from_germline += n_germ_to_33

    new_dir_from_untagged += n_unt_to_dir

    sanity_rows.append({
        "site_id": sid,
        "chrom": chrom,
        "pos": pos,
        "class": klass,
        "n_reads_v3f": len(v3),
        "n_reads_v5": len(v5),
        "v3_hp1": n_v3_1, "v5_hp1": n_v5_1,
        "v3_hp2": n_v3_2, "v5_hp2": n_v5_2,
        "v3_hp11": n_v3_11, "v5_hp11": n_v5_11,
        "v3_hp21": n_v3_21, "v5_hp21": n_v5_21,
        "v3_hp33": n_v3_33, "v5_hp33": n_v5_33,
        "delta_hp11": d_11,
        "delta_hp21": d_21,
        "delta_hp33": d_33,
        "n_33to11": n_33to11,
        "n_33to21": n_33to21,
        "n_germline_to_33": n_germ_to_33,
        "n_germline_changed_any": n_germ_changed,
        "n_untagged_to_directional": n_unt_to_dir,
        "law_A_delta_consistency": "PASS" if law_a_pass else "FAIL",
        "law_B_germline_unchanged": "PASS" if law_b_pass else "FAIL",
        "layer15_pred1_directional_source": "PASS" if layer15_pred1_pass else "FAIL",
        "layer15_pred2_no_germline_demote": "PASS" if layer15_pred2_pass else "FAIL",
    })

    # ----- Paired ground-truth ---------------------------------------------
    swap, germ_acc, germ_n = pick_orientation(v3, pa)
    # PS-class label per spec: clean ≥ 0.70, problem < 0.70 (matches PI report 4).
    ps_class = "clean" if germ_n >= 5 and germ_acc >= 0.70 else "problem"
    if germ_n < 3:
        ps_class = "low_germ_n"

    # Per-read concordance for V5 and BL on common subset (BL ∩ V5 ∩ Paired).
    common_bvp = set(bl) & set(v5) & set(pa)
    sub_bl = {rn: bl[rn] for rn in common_bvp}
    sub_v5 = {rn: v5[rn] for rn in common_bvp}
    sub_pa = {rn: pa[rn] for rn in common_bvp}

    m_v5, t_v5 = read_concordance(sub_v5, sub_pa, swap=swap)
    m_bl, t_bl = read_concordance(sub_bl, sub_pa, swap=swap)

    paired_rows.append({
        "site_id": sid,
        "chrom": chrom,
        "pos": pos,
        "class": klass,
        "n_common_reads": len(common_bvp),
        "germline_n": germ_n,
        "germline_acc": round(germ_acc, 4) if not np.isnan(germ_acc) else float("nan"),
        "ps_class": ps_class,
        "swap_paired_orientation": swap,
        "v5_match": m_v5, "v5_total": t_v5,
        "v5_concordance": round(m_v5 / t_v5, 4) if t_v5 else float("nan"),
        "bl_match": m_bl, "bl_total": t_bl,
        "bl_concordance": round(m_bl / t_bl, 4) if t_bl else float("nan"),
        "v5_minus_bl": (
            round(m_v5 / t_v5 - m_bl / t_bl, 4) if (t_v5 and t_bl) else float("nan")
        ),
    })


