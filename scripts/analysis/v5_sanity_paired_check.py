def determine_verdict() -> str:
    if (delta_consistency_violations == 0 and germline_change_violations == 0
            and layer15_pred1_violations == 0 and new_dir_from_germline == 0):
        return "PASS"
    # Soft warn if only the (informational) untagged→directional bucket is non-zero.
    if (delta_consistency_violations == 0 and germline_change_violations == 0
            and layer15_pred1_violations == 0):
        return "WARN"
    return "FAIL"


